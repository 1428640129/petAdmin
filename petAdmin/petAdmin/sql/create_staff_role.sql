    `role_key` = 'staff',
    `remark` = '店员角色，负责处理预约、订单等日常业务操作';

-- ============================================
-- 2. 为店员角色分配菜单权限
-- ============================================
-- 删除店员角色原有的菜单权限（如果存在）
DELETE FROM `sys_role_menu` WHERE `role_id` = 3;

-- 店员可以访问的菜单权限：
-- 1. 预约管理（2002）- 查看、确认、取消、开始服务、完成服务
