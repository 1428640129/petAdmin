-- ============================================
-- 权限说明
-- ============================================
-- 管理员（role_id=1）：
--   - 拥有所有权限（系统管理 + 业务管理）
--   - 可以管理用户、角色、菜单等系统设置
--   - 可以管理服务、预约、订单等所有业务
--
-- 店员（role_id=3）：
--   - 只能访问业务管理模块
--   - 可以处理预约：查询、确认、取消、开始服务、完成服务
--   - 可以查看订单和支付记录（只读）
--   - 可以查看和回复评价
--   - 可以查看通知
--   - 不能访问：服务管理、系统管理、用户管理、角色管理等
--   - 不能删除订单、不能处理退款（需要管理员权限）





